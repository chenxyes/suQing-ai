import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const dir = mkdtempSync(join(tmpdir(), 'suqing-behavior-'));
process.env.DB_PATH = join(dir, 'test.db');
process.env.BEHAVIOR_ENABLED = 'true';
let db;
try {
  const database = await import('../src/db.mjs');
  db = database.getDb();
  assert.ok(db.prepare("SELECT name FROM sqlite_master WHERE name='behavior_deliveries'").get(), 'migration must create independent behavior ledger');
  assert.ok(existsSync(new URL('../src/behavior_tasks.mjs', import.meta.url)), 'behavior task runtime exists');
  const { recordBehaviorDelivery: record, readBehaviorState: read, observeBehaviorInput: observe, claimDueBehaviorTask: claim, finishBehaviorTask: finish, isBehaviorTaskCurrent: current } = await import('../src/behavior_tasks.mjs');
  db.prepare("INSERT INTO users(id,wechat_user_id) VALUES(1,'fixture-1'),(2,'fixture-2')").run();
  db.prepare("INSERT INTO companions(id,user_id,bot_id,proactive_enabled) VALUES(1,1,'b',1),(2,2,'b',1)").run();
  db.prepare("INSERT INTO wechat_accounts(wechat_user_id,bot_id,bot_token,is_active) VALUES('fixture-1','b','test',1),('fixture-2','b','test',1)").run();
  const now = 1_800_000_000_000;
  const plan = { scenario: 'support', action: 'listen', sourceId: 'support-listen', sourceRevision: 'abc123', arcState: 'normal', followup: { delayMinutes: 10 } };
  const input = { companionId: 1, turnKey: 'turn1', plan, userText: '我很难过，10分钟后再问我，手机号13812345678', deliveredText: '好，待会儿来陪你。', channel: 'wechat', now };
  assert.ok(record(input));
  assert.equal(record(input).id, record(input).id);
  assert.equal(db.prepare('SELECT count(*) n FROM behavior_deliveries').get().n, 1, 'idempotent turn');
  assert.equal(db.prepare('SELECT count(*) n FROM behavior_followup_tasks').get().n, 1, 'idempotent promise');
  assert.equal(read(1, { now }).scenario, 'support');
  assert.equal(read(2, { now }), null, 'companion isolation');
  assert.ok(!db.prepare('SELECT context_text FROM behavior_deliveries').get().context_text.includes('13812345678'));
  assert.equal(record({ ...input, turnKey: 'probe', probe: true }), null);
  assert.equal(record({ ...input, turnKey: 'secret', userText: '密码是abcd1234' }), null);
  assert.equal(record({ ...input, turnKey: 'empty', deliveredText: '' }), null);
  assert.equal(record({ ...input, companionId: 999, turnKey: 'bad' }), null);
  assert.equal(claim(1, { now: now + 599999 }), null, 'not before due');
  observe(1, '好', { now: now + 1 });
  const task = claim(1, { now: now + 600000 });
  assert.ok(task, 'short ack preserves explicit promise');
  assert.equal(claim(1, { now: now + 600001 }), null, 'lease prevents concurrent claim');
  assert.equal(current(task, { now: now + 600001 }), true);
  assert.equal(current({ ...task, lease_token: 'bad' }, { now: now + 600001 }), false);
  assert.equal(finish(task, { status: 'failed', now: now + 600002 }), true);
  assert.equal(claim(1, { now: now + 600003 }), null, 'retry backoff');
  const retry = claim(1, { now: now + 1200002 });
  assert.ok(retry, 'failed send remains retryable');
  assert.equal(finish(task, { status: 'sent', deliveredText: 'stale', now: now + 1200003 }), false, 'old lease cannot complete');
  finish(retry, { status: 'partial', deliveredText: '现在好些了吗', now: now + 1200004 });
  assert.equal(claim(1, { now: now + 1800000 }), null, 'partial must not resend full message');
  assert.equal(db.prepare('SELECT status,delivered_text FROM behavior_followup_tasks').get().status, 'partial');
  record({ ...input, turnKey: 'cancel', now: now + 2000000 });
  const cancel = claim(1, { now: now + 2600000 });
  observe(1, '别再问这件事了', { now: now + 2600001 });
  assert.equal(current(cancel, { now: now + 2600002 }), false, 'cancel after generation invalidates claim');
  assert.equal(read(1, { now: now + 2600002 }).scenario, 'pause', 'stop tombstone prevents history fallback from reviving continuation');
  assert.equal(record({ ...input, turnKey: 'late-old-turn', inputStartedAt: now + 2_500_000, now: now + 2_700_000 }), null, 'old in-flight reply must not resurrect a cancelled promise');
  assert.equal(read(1, { now: now + 2_700_001 }).scenario, 'pause');
  record({ ...input, turnKey: 'web', channel: 'web', companionId: 2, now });
  assert.equal(claim(2, { now: now + 600000 }), null, 'web cannot schedule');
  record({ ...input, turnKey: 'invented', userText: '我难过', companionId: 2, now });
  assert.equal(claim(2, { now: now + 600000 }), null, 'model cannot invent permission');
  record({ ...input, turnKey: 'expire', now: now + 3000000 });
  assert.equal(claim(1, { now: now + 86400000 }), null, 'late task expires');
  record({ ...input, turnKey: 'restart', companionId: 2, now: now + 4000000 });
  const child = spawnSync(process.execPath, ['--input-type=module', '-e', `const b=await import('./src/behavior_tasks.mjs'); if(!b.readBehaviorState(2,{now:${now + 4000001}}))process.exit(1); const t=b.claimDueBehaviorTask(2,{now:${now + 4600000}}); if(!t)process.exit(2);`], { cwd: new URL('..', import.meta.url), env: process.env, encoding: 'utf8' });
  assert.equal(child.status, 0, `restart preserves task/state: ${child.stderr}`);
  record({ ...input, turnKey: 'lease-recovery', now: now + 10_000_000 });
  const lease = claim(1, { now: now + 10_600_000 });
  const recovered = claim(1, { now: now + 10_900_001 });
  assert.ok(recovered && recovered.lease_token !== lease.lease_token, 'expired lease can recover after worker death');
  observe(1, '好', { probe: true, safetyLevel: 'high', now: now + 10_900_002 });
  assert.equal(current(recovered, { now: now + 10_900_003 }), true, 'probe cannot cancel');
  observe(1, '我现在很危险', { safetyLevel: 'high', now: now + 10_900_004 });
  assert.equal(current(recovered, { now: now + 10_900_005 }), false, 'new safety risk cancels pending followup');
  record({ ...input, turnKey: 'disabled-push', now: now + 11_000_000 });
  db.prepare('UPDATE companions SET proactive_enabled=0 WHERE id=1').run();
  assert.equal(claim(1, { now: now + 11_600_000 }), null, 'disabled proactive cancels task');
  assert.equal(db.prepare("SELECT status FROM behavior_followup_tasks ORDER BY id DESC LIMIT 1").get().status, 'cancelled');
  db.prepare('UPDATE companions SET proactive_enabled=1 WHERE id=1').run();
  record({ ...input, turnKey: 'rebinding', now: now + 12_000_000 });
  db.prepare("INSERT INTO companions(id,user_id,bot_id,proactive_enabled) VALUES(3,1,'b',1)").run();
  db.prepare("UPDATE wechat_accounts SET companion_id=3 WHERE wechat_user_id='fixture-1'").run();
  assert.equal(claim(1, { now: now + 12_600_000 }), null, 'rebinding must cancel old companion task');
  db.prepare("UPDATE wechat_accounts SET companion_id=1 WHERE wechat_user_id='fixture-1'").run();
  for (const userText of ['他说10分钟后再找我', '我没说10分钟后再问我', '不要10分钟后再陪我']) {
    record({ ...input, turnKey: userText, userText, now: now + 13_000_000 });
    assert.equal(claim(1, { now: now + 13_600_000 }), null, 'reported/denied delay cannot authorize a task');
  }
  process.env.BEHAVIOR_ENABLED = 'false';
  assert.equal(record({ ...input, turnKey: 'off' }), null);
  assert.equal(read(1, { now }), null);
  console.log('behavior tasks: isolation, privacy, idempotency, probe, authorization, due, leases, cancel, failure, partial, expiry, restart and off passed');
} finally {
  db?.close();
  rmSync(dir, { recursive: true, force: true });
}
